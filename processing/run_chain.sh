# Stage out files via XRootD
stage_out() {
    local local_file="$1"
    local remote_subpath="$2"
    
    if [[ ! -f "${local_file}" ]]; then
        msg_error "Local file not found: ${local_file}"
        return 1
    fi
    
    local remote_url="${EOS_BASE}/${remote_subpath}"
    msg_info "Staging out: ${local_file} -> ${remote_url}"
    
    run_logged "xrdcp_stageout_$(basename "${local_file}")" run_xrdcp --nopbar --force "${local_file}" "${remote_url}" || {
        msg_error "Failed to stage out ${local_file} to ${remote_url}"
        return 1
    }
    msg_ok "Staged out: ${remote_url}"
}

get_lhe_file() {
    local pool_name="$1"
    local index="$2"
    local pool_subpath=""
    local files=()
    local n_files=0
    local file_idx=0

    if ! mapfile -t files < <(list_lhe_files "${pool_name}"); then
        return 1
    fi

    n_files=${#files[@]}
    if [[ ${n_files} -eq 0 ]]; then
        if [[ -n "${EXISTING_POOLS[$pool_name]}" ]]; then
            pool_subpath="${EXISTING_POOLS[$pool_name]}"
        else
            pool_subpath="lhe_pools/${pool_name}"
        fi
        msg_error "No LHE files found in ${EOS_PATH_BASE}/${pool_subpath}" >&2
        return 1
    fi

    file_idx=$((index % n_files))
    echo "${files[$file_idx]}"
}

list_lhe_files() {
    local pool_name="$1"
    local pool_subpath=""
    local file_list=""

    if [[ -n "${EXISTING_POOLS[$pool_name]}" ]]; then
        pool_subpath="${EXISTING_POOLS[$pool_name]}"
    else
        pool_subpath="lhe_pools/${pool_name}"
    fi

    if ! file_list=$(run_xrdfs "${EOS_XRDFS_TARGET}" ls "${EOS_PATH_BASE}/${pool_subpath}" 2>/dev/null | grep '\.lhe$' | sort); then
        msg_error "Failed to list LHE files via xrdfs at ${EOS_PATH_BASE}/${pool_subpath}" >&2
        return 1
    fi

    if [[ -z "${file_list}" ]]; then
        return 0
    fi

    while IFS= read -r line; do
        [[ -n "${line}" ]] || continue
        printf 'root://%s/%s\n' "${EOS_HOST}" "${line}"
    done <<< "${file_list}"
}

extract_lhe_cross_section_pb() {
    local lhe_file="$1"
    awk '
        /<init>/ { in_init=1; next }
        in_init && seen_header == 0 {
            if (NF > 0) {
                seen_header = 1
            }
            next
        }
        in_init && seen_header == 1 && NF > 0 {
            print $1
            exit
        }
    ' "${lhe_file}"
}

estimate_pool_cross_section_pb() {
    local pool_name="$1"
    local sample_url="$2"
    local cache_file="${WORKDIR}/.xsec_${pool_name}.txt"
    local sample_file="${WORKDIR}/.${pool_name}_xsec_sample.lhe"
    local xsec=""
    local cleanup_sample=0

    mkdir -p "${WORKDIR}"

    if [[ -f "${cache_file}" ]]; then
        cat "${cache_file}"
        return 0
    fi

    if [[ "${sample_url}" == root://* ]]; then
        if ! run_xrdcp --nopbar --force "${sample_url}" "${sample_file}" >/dev/null 2>&1; then
            return 1
        fi
        cleanup_sample=1
    else
        sample_file="${sample_url}"
    fi

    if [[ -f "${sample_file}" ]]; then
        xsec=$(extract_lhe_cross_section_pb "${sample_file}" | head -n 1)
    fi

    if [[ ${cleanup_sample} -eq 1 ]]; then
        rm -f "${sample_file}"
    fi

    if [[ -z "${xsec}" ]]; then
        return 1
    fi

    printf '%s\n' "${xsec}" > "${cache_file}"
    printf '%s\n' "${xsec}"
}

select_composite_variant() {
    local pool_name="$1"
    local job_index="$2"
    local usage_index="$3"
    local variants_csv="${COMPOSITE_POOL_VARIANTS[$pool_name]:-}"
    local variants=()
    local active_variants=()
    local active_weights=()
    local variant=""
    local files=()
    local weight=""
    local selected_variant=""
    local selector_key=0
    local index=0

    if [[ -z "${variants_csv}" ]]; then
        msg_error "Composite pool is not configured: ${pool_name}" >&2
        return 1
    fi

    IFS=',' read -ra variants <<< "${variants_csv}"

    for variant in "${variants[@]}"; do
        if ! mapfile -t files < <(list_lhe_files "${variant}"); then
            return 1
        fi
        if [[ ${#files[@]} -eq 0 ]]; then
            msg_warn "Composite sub-pool has no files and will be skipped: ${variant}" >&2
            continue
        fi

        if ! weight=$(estimate_pool_cross_section_pb "${variant}" "${files[0]}"); then
            weight="1.0"
            msg_warn "Failed to extract cross section for ${variant}; fallback to equal weight" >&2
        fi

        active_variants+=("${variant}")
        active_weights+=("${weight}")
    done

    if [[ ${#active_variants[@]} -eq 0 ]]; then
        msg_error "No usable sub-pool found for composite pool ${pool_name}" >&2
        return 1
    fi

    if [[ ${#active_variants[@]} -eq 1 ]]; then
        printf '%s\n' "${active_variants[0]}"
        return 0
    fi

    selector_key=$(( (job_index + 1) * 104729 + (usage_index + 1) * 1009 ))
    selected_variant=$(awk \
        -v variants="$(IFS=,; echo "${active_variants[*]}")" \
        -v weights="$(IFS=,; echo "${active_weights[*]}")" \
        -v key="${selector_key}" \
        'BEGIN {
            n = split(variants, v, ",")
            split(weights, w, ",")
            total = 0.0
            for (i = 1; i <= n; ++i) {
                total += (w[i] + 0.0)
            }
            if (total <= 0.0) {
                print v[1]
                exit
            }
            frac = ((key * 1103515245 + 12345) % 1000000) / 1000000.0
            acc = 0.0
            for (i = 1; i <= n; ++i) {
                acc += (w[i] + 0.0) / total
                if (frac < acc) {
                    print v[i]
                    exit
                }
            }
            print v[n]
        }')

    if [[ -z "${selected_variant}" ]]; then
        selected_variant="${active_variants[0]}"
    fi

    for index in "${!active_variants[@]}"; do
        if [[ "${active_variants[$index]}" == "${selected_variant}" ]]; then
            msg_info "Composite pool ${pool_name}: selected ${selected_variant} (sigma=${active_weights[$index]} pb)" >&2
            break
        fi
    done

    printf '%s\n' "${selected_variant}"
}

resolve_composite_lhe_file() {
    local pool_name="$1"
    local job_index="$2"
    local usage_index="$3"
    local selected_variant=""
    local selected_file=""
    local variant_file_index=0

    selected_variant=$(select_composite_variant "${pool_name}" "${job_index}" "${usage_index}") || return 1
    variant_file_index=$((job_index + usage_index))
    selected_file=$(get_lhe_file "${selected_variant}" "${variant_file_index}") || return 1
    printf '%s\n' "${selected_file}"
}

# Check if a remote XRootD file exists
check_remote_file() {
    local url="$1"
    if [[ "$url" == root://* ]]; then
        # Extract host and path from XRootD URL
        local host_path="${url#root://}"
        local host="${host_path%%/*}"
        local path="/${host_path#*/}"
        run_xrdfs "root://${host}" stat "${path}" &>/dev/null
        return $?
    else
        # Local file check
        [[ -f "$url" ]]
        return $?
    fi
}

