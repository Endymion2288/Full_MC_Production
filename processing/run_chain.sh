BUILDEOF
        chmod +x "${tmp_script}"
        
        run_logged "apptainer_scram_b_${ANALYSIS_TYPE}" apptainer exec \
            --bind /cvmfs:/cvmfs \
            --bind /tmp:/tmp \
            --bind "${WORKDIR}:${WORKDIR}" \
            "${EL9_CONTAINER}" \
            /bin/bash "${tmp_script}"
        rm -f "${tmp_script}"
        
        touch "${stamp}"
    else
        msg_info "Reusing existing CMSSW_15_0_15 build for ${analysis}"
    fi
}

